"""Deterministic generated-file and marker-region writer."""

from __future__ import annotations

from pathlib import Path

HEADER = "# Generated by scripts/codegen.py from mutations.graphql -- do not edit.\n"


def write_if_changed(path: Path, content: str) -> bool:
    normalized = content.replace("\r\n", "\n")
    if not normalized.endswith("\n"):
        normalized += "\n"
    current = path.read_text(encoding="utf-8") if path.exists() else None
    if current == normalized:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(normalized, encoding="utf-8", newline="\n")
    return True


def splice_region(path: Path, start: str, end: str, body: str) -> bool:
    if not path.exists():
        return False
    current = path.read_text(encoding="utf-8")
    start_at = current.find(start)
    end_at = current.find(end)
    if start_at < 0 or end_at < start_at:
        raise ValueError(f"Missing or invalid AUTOGEN markers in {path}")
    block = f"{start}\n\n{body.rstrip()}\n\n{end}"
    updated = current[:start_at] + block + current[end_at + len(end) :]
    if updated == current:
        return False
    path.write_text(updated, encoding="utf-8", newline="\n")
    return True
